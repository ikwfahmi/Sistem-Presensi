-- Jalankan sekali pada proyek Supabase baru melalui SQL Editor.
begin;
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null check (length(trim(name)) between 1 and 160),
  identifier text not null unique check (identifier ~ '^[a-z0-9._-]{1,80}$'),
  role text not null check (role in ('admin','baak','dosen','mahasiswa'))
);
create table public.classes (
  id bigint generated by default as identity primary key,
  code text not null unique check (length(trim(code)) between 1 and 40),
  name text not null check (length(trim(name)) between 1 and 160),
  lecturer_id uuid not null references public.profiles(id),
  room text not null check (length(trim(room)) between 1 and 100),
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  radius integer not null default 50 check (radius between 10 and 500)
);
create table public.enrollments (
  class_id bigint references public.classes(id) on delete cascade,
  student_id uuid references public.profiles(id) on delete cascade,
  primary key (class_id,student_id)
);
create table public.sessions (
  id bigint generated by default as identity primary key,
  class_id bigint not null references public.classes(id), title text not null check (length(trim(title)) between 1 and 160),
  starts_at timestamptz not null, ends_at timestamptz not null, closed boolean not null default false,
  latitude double precision not null, longitude double precision not null, radius integer not null,
  check (ends_at > starts_at and ends_at <= starts_at + interval '24 hours'),
  check (latitude between -90 and 90 and longitude between -180 and 180 and radius between 10 and 500)
);
create table public.attendance (
  id bigint generated by default as identity primary key,
  session_id bigint not null references public.sessions(id), student_id uuid not null references public.profiles(id),
  recorded_at timestamptz not null default now(), latitude double precision not null,
  longitude double precision not null, accuracy double precision not null, distance double precision not null,
  unique (session_id,student_id)
);
create table public.attempts (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id), session_id bigint not null references public.sessions(id),
  occurred_at timestamptz not null default now(), reason text not null
);
create table public.challenges (
  student_id uuid not null references public.profiles(id) on delete cascade,
  session_id bigint not null references public.sessions(id) on delete cascade,
  token uuid not null default gen_random_uuid(), created_at timestamptz not null default now(),
  primary key (student_id,session_id)
);
create index on public.classes(lecturer_id);
create index on public.enrollments(student_id);
create index on public.sessions(class_id,starts_at);
create index on public.attendance(student_id);
create index on public.attempts(session_id,occurred_at);

-- Definer helpers avoid recursive RLS checks. No caller-supplied user ID.
create function public.current_role() returns text language sql stable security definer set search_path = '' as $$
  select role from public.profiles where id = (select auth.uid());
$$;
create function public.can_read_class(cid bigint) returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.classes c where c.id=cid and (
    public.current_role() in ('admin','baak') or c.lecturer_id=(select auth.uid()) or
    exists(select 1 from public.enrollments e where e.class_id=c.id and e.student_id=(select auth.uid()))));
$$;
create function public.can_manage_class(cid bigint) returns boolean language sql stable security definer set search_path = '' as $$
  select public.current_role()='admin' or (public.current_role()='dosen' and exists(
    select 1 from public.classes where id=cid and lecturer_id=(select auth.uid())));
$$;
alter table public.profiles enable row level security;
alter table public.classes enable row level security;
alter table public.enrollments enable row level security;
alter table public.sessions enable row level security;
alter table public.attendance enable row level security;
alter table public.attempts enable row level security;
alter table public.challenges enable row level security;
create policy profiles_read on public.profiles for select to authenticated using (
  id=(select auth.uid()) or public.current_role() in ('admin','baak','dosen') or
  exists(select 1 from public.classes c where c.lecturer_id=profiles.id and public.can_read_class(c.id))
);
create policy classes_read on public.classes for select to authenticated using (public.can_read_class(id));
create policy enrollment_read on public.enrollments for select to authenticated using (
  student_id=(select auth.uid()) or public.can_manage_class(class_id) or public.current_role()='baak'
);
create policy sessions_read on public.sessions for select to authenticated using (public.can_read_class(class_id));
create policy attendance_read on public.attendance for select to authenticated using (
  student_id=(select auth.uid()) or exists(select 1 from public.sessions s where s.id=session_id and
    (public.can_manage_class(s.class_id) or public.current_role()='baak'))
);
create policy attempts_read on public.attempts for select to authenticated using (
  public.current_role()='admin' or exists(select 1 from public.sessions s where s.id=session_id and public.can_manage_class(s.class_id))
);
-- No write policies: all writes pass explicit authorization in narrow RPCs.
revoke all on public.profiles,public.classes,public.enrollments,public.sessions,public.attendance,public.attempts,public.challenges from anon,authenticated;
grant select on public.profiles,public.classes,public.enrollments,public.sessions,public.attendance,public.attempts to authenticated;
grant all on public.profiles,public.classes,public.enrollments,public.sessions,public.attendance,public.attempts,public.challenges to service_role;
grant usage,select on all sequences in schema public to service_role;

create function public.save_class(p_id bigint,p_code text,p_name text,p_lecturer uuid,p_room text,p_lat double precision,p_lng double precision,p_radius integer)
returns bigint language plpgsql security definer set search_path = '' as $$
declare result bigint;
begin
  if public.current_role() not in ('admin','dosen') or public.current_role() is null then raise exception 'Akses ditolak'; end if;
  if p_id is not null and not public.can_manage_class(p_id) then raise exception 'Kelas tidak tersedia'; end if;
  if public.current_role()='dosen' and p_lecturer<>auth.uid() then raise exception 'Dosen hanya dapat mengelola kelas sendiri'; end if;
  if not exists(select 1 from public.profiles where id=p_lecturer and role='dosen') then raise exception 'Pilih dosen pengampu'; end if;
  if p_id is null then
    insert into public.classes(code,name,lecturer_id,room,latitude,longitude,radius)
    values(p_code,p_name,p_lecturer,p_room,p_lat,p_lng,p_radius) returning id into result;
  else
    update public.classes set code=p_code,name=p_name,lecturer_id=p_lecturer,room=p_room,latitude=p_lat,longitude=p_lng,radius=p_radius where id=p_id returning id into result;
  end if;
  return result;
end;
$$;
create function public.enroll_student(p_class bigint,p_student uuid) returns void language plpgsql security definer set search_path = '' as $$
begin
  if not coalesce(public.can_manage_class(p_class),false) then raise exception 'Akses ditolak'; end if;
  if not exists(select 1 from public.profiles where id=p_student and role='mahasiswa') then raise exception 'Pilih mahasiswa'; end if;
  insert into public.enrollments values(p_class,p_student) on conflict do nothing;
end;
$$;
create function public.create_session(p_class bigint,p_title text,p_start timestamptz,p_end timestamptz)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if not coalesce(public.can_manage_class(p_class),false) then raise exception 'Akses ditolak'; end if;
  insert into public.sessions(class_id,title,starts_at,ends_at,latitude,longitude,radius)
    select id,p_title,p_start,p_end,latitude,longitude,radius from public.classes where id=p_class;
end;
$$;
create function public.close_session(p_session bigint) returns void language plpgsql security definer set search_path = '' as $$
begin
  if not exists(select 1 from public.sessions where id=p_session and public.can_manage_class(class_id)) then raise exception 'Akses ditolak'; end if;
  update public.sessions set closed=true where id=p_session;
end;
$$;
create function public.issue_challenge(p_session bigint) returns uuid language plpgsql security definer set search_path = '' as $$
declare result uuid;
begin
  if public.current_role() is distinct from 'mahasiswa' or not exists(
    select 1 from public.sessions s join public.enrollments e on e.class_id=s.class_id
    where s.id=p_session and e.student_id=auth.uid() and not s.closed and now() between s.starts_at and s.ends_at
  ) then raise exception 'Sesi belum dibuka, sudah berakhir, atau Anda bukan peserta'; end if;
  insert into public.challenges(student_id,session_id) values(auth.uid(),p_session)
  on conflict(student_id,session_id) do update set token=gen_random_uuid(),created_at=now() returning token into result;
  return result;
end;
$$;
create function public.submit_attendance(p_session bigint,p_token uuid,p_lat double precision,p_lng double precision,p_accuracy double precision,p_timestamp double precision,p_mock boolean default false)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare s public.sessions; ch public.challenges; reason text; d double precision; a double precision;
begin
  if public.current_role() is distinct from 'mahasiswa' then raise exception 'Akses ditolak'; end if;
  -- Serialize with closing the session and lock the challenge before consuming it.
  select * into s from public.sessions where id=p_session for share;
  if s.id is null or not exists(select 1 from public.enrollments where class_id=s.class_id and student_id=auth.uid()) then raise exception 'Anda bukan peserta sesi'; end if;
  select * into ch from public.challenges where student_id=auth.uid() and session_id=p_session for update;
  delete from public.challenges where student_id=auth.uid() and session_id=p_session;
  if ch.token is null or ch.token is distinct from p_token or now()-ch.created_at>interval '60 seconds' then reason:='Token presensi tidak valid atau kedaluwarsa';
  elsif s.closed or now()<s.starts_at or now()>s.ends_at then reason:='Sesi belum dibuka atau sudah berakhir';
  elsif p_lat is null or p_lng is null or p_accuracy is null or p_timestamp is null or
    not (p_lat between -90 and 90 and p_lng between -180 and 180 and p_accuracy>0 and p_accuracy<=least(50,s.radius))
    or p_timestamp='NaN'::float8 or abs(extract(epoch from now())-p_timestamp/1000)>30 then reason:='Lokasi tidak valid, kedaluwarsa, atau GPS kurang akurat';
  elsif coalesce(p_mock,false) then reason:='Lokasi tiruan terlapor';
  else
    a:=power(sin(radians(s.latitude-p_lat)/2),2)+cos(radians(p_lat))*cos(radians(s.latitude))*power(sin(radians(s.longitude-p_lng)/2),2);
    d:=6371000*2*atan2(sqrt(least(1,a)),sqrt(greatest(0,1-a)));
    if d>s.radius then reason:='Anda berada di luar radius presensi ('||round(d)::text||' meter)'; end if;
  end if;
  if reason is null then
    insert into public.attendance(session_id,student_id,latitude,longitude,accuracy,distance)
      values(p_session,auth.uid(),p_lat,p_lng,p_accuracy,d) on conflict(session_id,student_id) do nothing;
    if not found then reason:='Anda sudah melakukan presensi'; end if;
  end if;
  if reason is not null then
    insert into public.attempts(student_id,session_id,reason) values(auth.uid(),p_session,reason);
    return jsonb_build_object('ok',false,'message',reason);
  end if;
  return jsonb_build_object('ok',true,'message','Presensi berhasil dicatat','distance',d);
end;
$$;
-- Invoker view retains RLS, including absent students and pending sessions.
create view public.attendance_report with (security_invoker=true) as
select s.id session_id,c.id class_id,c.code,c.name class_name,s.title,s.starts_at,s.ends_at,s.closed,
  p.id student_id,p.name,p.identifier,a.recorded_at,a.distance,a.accuracy,
  case when a.id is not null then 'Hadir' when s.closed or s.ends_at<now() then 'Tidak hadir' else 'Belum presensi' end status
from public.sessions s join public.classes c on c.id=s.class_id
join public.enrollments e on e.class_id=c.id join public.profiles p on p.id=e.student_id
left join public.attendance a on a.session_id=s.id and a.student_id=p.id;
grant select on public.attendance_report to authenticated;
-- PostgreSQL grants execute to PUBLIC by default: restrict every application function.
revoke execute on function public.current_role(), public.can_read_class(bigint),public.can_manage_class(bigint),
