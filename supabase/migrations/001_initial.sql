  public.enroll_student(bigint,uuid),public.create_session(bigint,text,timestamptz,timestamptz),
  public.close_session(bigint),public.issue_challenge(bigint),
  public.submit_attendance(bigint,uuid,double precision,double precision,double precision,double precision,boolean) from public,anon;
grant execute on function public.current_role(),public.can_read_class(bigint),public.can_manage_class(bigint),
  public.save_class(bigint,text,text,uuid,text,double precision,double precision,integer),
  public.enroll_student(bigint,uuid),public.create_session(bigint,text,timestamptz,timestamptz),
  public.close_session(bigint),public.issue_challenge(bigint),
  public.submit_attendance(bigint,uuid,double precision,double precision,double precision,double precision,boolean) to authenticated;
commit;
